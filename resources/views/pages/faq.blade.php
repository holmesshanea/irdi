                        a unique link they can use to submit their review.
                    </p>
                </flux:accordion.item>


                <flux:accordion.item heading="Does a property owner need an IRDI account to leave a review?">
                    <p class="text-sm leading-6 text-zinc-600 dark:text-zinc-400">
                        No. Property owners do not need to become IRDI Members or create an IRDI
                        account in order to respond to a valid Property Owner Review invitation.
                    </p>
                </flux:accordion.item>


                <flux:accordion.item heading="What does a Property Owner Review ask about?">
                    <p class="text-sm leading-6 text-zinc-600 dark:text-zinc-400">
                        Property Owner Reviews focus on the member's respect for the property,
                        communication and courtesy, care of the property, and whether the property
                        owner would allow the detectorist to return. The property owner may also
                        provide written comments.
                    </p>
                </flux:accordion.item>


                <flux:accordion.item heading="Can anyone leave a review on my profile?">
                    <p class="text-sm leading-6 text-zinc-600 dark:text-zinc-400">
                        No. Property Owner Reviews are submitted through unique review invitations
                        associated with an IRDI Member Profile rather than through an unrestricted
                        public review form.
                    </p>
                </flux:accordion.item>


                <flux:accordion.item heading="How long does a review invitation remain available?">
                    <p class="text-sm leading-6 text-zinc-600 dark:text-zinc-400">
                        A Property Owner Review invitation is available for a limited period.
                        Invitations currently expire 30 days after they are created and are
                        intended for a single review.
                    </p>
                </flux:accordion.item>


                <flux:accordion.item heading="Can the same review invitation be used more than once?">
                    <p class="text-sm leading-6 text-zinc-600 dark:text-zinc-400">
                        No. Review invitations are intended for one-time use. Once a review has
                        been successfully submitted through an invitation, that invitation cannot
                        be used to submit another review.
                    </p>
                </flux:accordion.item>


                <flux:accordion.item heading="What review information appears on my public profile?">
                    <p class="text-sm leading-6 text-zinc-600 dark:text-zinc-400">
                        IRDI may summarize your visible Property Owner Reviews on your public
                        Member Profile, including the number of reviews, an overall review rating,
                        and information about whether property owners would allow you to return.
                    </p>
